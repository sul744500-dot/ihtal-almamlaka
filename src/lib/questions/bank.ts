// بنك الأسئلة الافتراضي — الخيار الأول في كل مصفوفة هو الإجابة الصحيحة،
// ثم تُخلط الخيارات بترتيب ثابت (حسب معرّف السؤال) حتى لا تكون الإجابة دائمًا في المكان نفسه.

import { hashString, mulberry32, shuffle } from '../rng';
import type { CategoryId, Difficulty, Question, QuestionMedia } from '../types';

interface Raw {
  d: Difficulty;
  q: string;
  /** الخيار الأول هو الصحيح. للأسئلة المفتوحة: عنصر واحد هو الإجابة */
  a: string[];
  n?: string;
  m?: QuestionMedia;
  open?: boolean;
}

/** الإصدار 2: مجموعة أسئلة جديدة بالكامل (تستبدل أسئلة الإصدار 1 غير المعدّلة) */
export const BANK_VERSION = 2;

function build(category: CategoryId, items: Raw[]): Question[] {
  return items.map((it, i) => {
    const id = `${category}-v2-${String(i + 1).padStart(2, '0')}`;
    if (it.open) {
      return {
        id,
        category,
        difficulty: it.d,
        type: 'open',
        text: it.q,
        options: [],
        correct: -1,
        answer: it.a[0],
        note: it.n,
        media: it.m,
      };
    }
    const order = shuffle(
      it.a.map((_, idx) => idx),
      mulberry32(hashString(id)),
    );
    const options = order.map((idx) => it.a[idx]);
    return {
      id,
      category,
      difficulty: it.d,
      type: 'mcq',
      text: it.q,
      options,
      correct: order.indexOf(0),
      answer: it.a[0],
      note: it.n,
      media: it.m,
    };
  });
}

